#!/usr/bin/env python3
"""grid_pdf.py — read the Local Dominator grid PDFs once and write a compact summary (S10).

    python3 scripts/grid_pdf.py <slug> [pdf ...] [--force]

The PDFs are large (images plus pages of advice) and expensive for an agent to read. This
extracts their text ONCE with macOS PDFKit and writes
clients/<slug>/data/local-grid/local-grid-summary.md — one section per PDF: keyword, view
(local pack / maps), grid size, the business's average rank, the rank grid as a small
table when the text holds one, the top competitors (rating, reviews, average rank) and the
scan date. Agents read the summary, never the PDFs.

Measured results only: the reports' written advice (summaries, action plans, "competitor
strategy") is not copied (audit-steps S10).

Default PDFs: every *.pdf under clients/<slug>/inputs/local-grid/ and clients/<slug>/data/local-grid/.
Nothing is extracted when the summary is newer than every PDF. A summary written by hand
(no grid_pdf.py marker) is never overwritten unless --force.

Text extraction backends, first that works: PyObjC (Quartz.PDFDocument), then the system
`osascript -l JavaScript` with the ObjC bridge to PDFKit. No poppler, no pip installs.
SEO_OPS_GRID_PDF_BACKEND=pyobjc|osascript|none forces one (tests use none).
Exit 0 written / up to date · 1 bad input or hand-written summary · 2 no extraction backend.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib import client_dir, die, now  # noqa: E402

MARKER = "<!-- generated by scripts/grid_pdf.py — do not edit; re-run it -->"
RANK = r"(?:\d{1,3}(?:\.\d+)?\+?)"
CELL = r"(?:\d{1,2}\+?|X|x|-|–|—)"

JXA = r'''
ObjC.import("PDFKit");
function run(argv) {
  var out = [];
  for (var i = 0; i < argv.length; i++) {
    var d = $.PDFDocument.alloc.initWithURL($.NSURL.fileURLWithPath(argv[i]));
    if (!d || d.isNil()) { out.push(null); continue; }
    var s = d.string;
    out.push((s && !s.isNil()) ? s.js : "");
  }
  return JSON.stringify(out);
}
'''


# ------------------------------------------------------------------ extraction
def _pyobjc(paths):
    from Foundation import NSURL  # noqa
    from Quartz import PDFDocument  # noqa
    out = []
    for p in paths:
        d = PDFDocument.alloc().initWithURL_(NSURL.fileURLWithPath_(str(p)))
        out.append(None if d is None else str(d.string() or ""))
    return out


def _osascript(paths):
    r = subprocess.run(["osascript", "-l", "JavaScript", "-e", JXA, *[str(p) for p in paths]],
                       capture_output=True, text=True, timeout=300)
    if r.returncode:
        raise RuntimeError((r.stderr or r.stdout).strip()[:300])
    return json.loads(r.stdout)


def extract(paths):
    """Text of each PDF (None where PDFKit could not open it). Raises LookupError when no
    backend works on this machine."""
    want = os.environ.get("SEO_OPS_GRID_PDF_BACKEND", "").strip().lower()
    tried = []
    for name, fn in (("pyobjc", _pyobjc), ("osascript", _osascript)):
        if want and want != name:
            continue
        try:
            return name, fn(paths)
        except Exception as e:  # noqa: BLE001 — try the next backend
            tried.append(f"{name}: {str(e)[:160]}")
    raise LookupError("; ".join(tried) or f"backend forced to '{want}'")


# ------------------------------------------------------------------ parsing
def parse(text):
    """Measured fields from a Local Dominator scan report's text."""
    text = (text or "").replace("\x00", " ").replace("\u00a0", " ")   # PDFKit gives NUL for some glyphs
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    joined = "\n".join(lines)
    r = {"business": lines[0] if lines else "", "location": "", "date": "", "view": "",
         "keyword": "", "avg_rank": "", "grid": "", "rank_grid": [], "competitors": []}
    if len(lines) > 1 and not lines[1].lower().startswith("scan"):
        r["location"] = lines[1]
    m = re.search(r"Scan date:\s*([^\n]+?)(?=\s+Scan Analysis|\n|$)", joined)
    if m:
        r["date"] = m.group(1).strip()
    m = re.search(r"Scan Analysis Report\s*(local pack|maps?|[a-z ]{0,20}?)(?=\n|\s+Primary|$)", joined, re.I)
    if m and m.group(1).strip():
        v = m.group(1).strip().lower()
        r["view"] = "Google Maps" if v.startswith("map") else ("Local pack" if "pack" in v else v)
    # keyword and average rank: "Primary keyword / Avg. Rank / <keyword> / <rank>"
    for i, ln in enumerate(lines):
        if ln.lower().startswith("primary keyword"):
            rest = lines[i + 1:i + 5]
            if rest and rest[0].lower().startswith("avg"):
                rest = rest[1:]
            if len(rest) >= 2 and re.fullmatch(RANK, rest[1]):
                r["keyword"], r["avg_rank"] = rest[0], rest[1]
            break
    if not r["keyword"]:
        m = re.search(r"Primary keyword\s+Avg\.?\s*Rank\s+(.+?)\s+(" + RANK + r")(?=\s|$)", joined, re.I | re.S)
        if m:
            r["keyword"], r["avg_rank"] = " ".join(m.group(1).split()), m.group(2)
    m = re.search(r"(\d+)\s*Pins\s*\|[^\d\n]*(\d+)\s*(?:[x×]\s*\d+\s*)?with\s*([\d.]+)\s*(mi|km|miles?)\s*spacing", joined, re.I)
    if m:
        n = m.group(2)
        r["grid"] = f"{m.group(1)} pins, {n} × {n}, {m.group(3)} {m.group(4)} spacing"
    # rank grid: three or more consecutive lines of rank cells, all the same width
    run_ = []
    for ln in lines + [""]:
        toks = ln.split()
        if len(toks) >= 3 and all(re.fullmatch(CELL, t) for t in toks) and (not run_ or len(toks) == len(run_[0])):
            run_.append(toks)
            continue
        if len(run_) >= 3 and len(run_) > len(r["rank_grid"]):
            r["rank_grid"] = run_
        run_ = [toks] if len(toks) >= 3 and all(re.fullmatch(CELL, t) for t in toks) else []
    # competitors: "<name>" / "<rating> (<reviews>)" / "<avg rank> <their description…>"
    try:
        start = next(i for i, ln in enumerate(lines) if re.match(r"Business Name\s+Avg", ln, re.I))
    except StopIteration:
        start = None
    if start is not None:
        for i in range(start + 1, len(lines) - 1):
            ln = lines[i]
            if re.match(r"(Competition Overview|To Reach|Smart Geo|Action Plan)", ln, re.I):
                break
            m = re.fullmatch(r"(\d(?:\.\d+)?)\s*\((\d[\d,]*)\)", ln)
            if not m:
                continue
            name = lines[i - 1]
            if i - 2 > start and lines[i - 2].count("(") > lines[i - 2].count(")"):
                name = lines[i - 2] + " " + name
            rk = re.match(RANK, lines[i + 1])
            r["competitors"].append({"name": name, "rating": m.group(1), "reviews": m.group(2),
                                     "avg_rank": rk.group(0) if rk else ""})
    return r


# ------------------------------------------------------------------ output
def render(slug, items, backend):
    out = [MARKER, "", f"# {slug} — local grid results (S10)", "",
           f"Generated {now()[:16].replace('T', ' ')} by `scripts/grid_pdf.py` from {len(items)} Local Dominator "
           f"PDF(s); text read once with macOS PDFKit ({backend}). **Measured results only** — the reports' "
           "written advice is not used; heat-map images are not read. Read this file, not the PDFs.", "",
           "| Keyword | View | Avg. rank | Grid | Scan date |", "|---|---|---|---|---|"]
    for p, r in items:
        if r is None:
            out.append(f"| (unreadable) `{p.name}` | | | | |")
            continue
        out.append(f"| {r['keyword'] or '?'} | {r['view'] or '?'} | **{r['avg_rank'] or '?'}** | "
                   f"{r['grid'] or '?'} | {r['date'] or '?'} |")
    for p, r in items:
        out += ["", f"## {(r or {}).get('keyword') or p.stem}" + (f" · {r['view']}" if r and r["view"] else ""), "",
                f"- **File:** `{p.name}`"]
        if r is None:
            out.append("- PDFKit could not open this file — check it by hand.")
            continue
        out += [f"- **Business:** {r['business'] or '?'} · **report location label:** {r['location'] or 'not stated'}",
                f"- **Scan date:** {r['date'] or 'not found in the text'}",
                f"- **Grid:** {r['grid'] or 'not found in the text'}",
                f"- **Average rank:** {r['avg_rank'] or 'not found in the text'}"]
        g = r["rank_grid"]
        if g:
            w = len(g[0])
            out += ["", "Rank grid (as printed in the text):", "",
                    "| " + " | ".join(f"c{c + 1}" for c in range(w)) + " |", "|" + "---|" * w]
            out += ["| " + " | ".join(row) + " |" for row in g]
        else:
            out.append("- **Rank grid:** not in the text (the heat map is an image)")
        if r["competitors"]:
            out += ["", "| Competitor | Rating (reviews) | Avg. rank |", "|---|---|---|"]
            out += [f"| {c['name']} | {c['rating']} ({c['reviews']}) | {c['avg_rank']} |" for c in r["competitors"]]
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    force = "--force" in args
    args = [a for a in args if a != "--force"]
    if not args or args[0] in ("-h", "--help"):
        print(__doc__)
        sys.exit(0 if args else 1)
    slug, given = args[0], args[1:]
    cd = client_dir(slug)
    out_dir = cd / "data" / "local-grid"
    summary = out_dir / "local-grid-summary.md"
    if given:
        pdfs = [Path(p) if Path(p).is_absolute() else Path.cwd() / p for p in given]
        missing = [str(p) for p in pdfs if not p.is_file()]
        if missing:
            die("These PDFs do not exist: " + "; ".join(missing))
    else:
        pdfs = sorted({p for d in (cd / "inputs" / "local-grid", out_dir) if d.is_dir()
                       for p in d.rglob("*.pdf")})
    if not pdfs:
        die(f"No local-grid PDFs found. Save the Local Dominator reports in "
            f"clients/{slug}/inputs/local-grid/ (or pass the files), then run this again.")
    if summary.exists() and not force:
        if summary.stat().st_mtime >= max(p.stat().st_mtime for p in pdfs):
            print(f"up to date — {summary.relative_to(cd.parent.parent)} is newer than all {len(pdfs)} PDF(s); "
                  "nothing extracted (--force to redo)")
            return
        if MARKER not in summary.read_text(errors="ignore"):
            die(f"{summary.name} was written by hand (no grid_pdf.py marker) and a PDF is newer. "
                "Not overwritten — move the old summary aside or re-run with --force.")
    try:
        backend, texts = extract(pdfs)
    except LookupError as e:
        die("Cannot read the PDFs: no macOS PDFKit backend works here (PyObjC not installed and "
            f"`osascript -l JavaScript` failed: {e}). Run this on the Mac, or read the PDFs by hand and "
            "write the summary. No summary was written.", 2)
    items = [(p, None if t is None else parse(t)) for p, t in zip(pdfs, texts)]
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = summary.with_suffix(".md.tmp")
    tmp.write_text(render(slug, items, backend))
    tmp.replace(summary)
    print(f"wrote {summary.relative_to(cd.parent.parent)} — {len(items)} PDF(s), backend {backend}")
    for p, r in items:
        print(f"  {p.name}: " + ("unreadable" if r is None else
                                 f"{r['keyword'] or '?'} · {r['view'] or '?'} · avg {r['avg_rank'] or '?'}"))


if __name__ == "__main__":
    main()
